create table public.hydro_products (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  short_name text not null,
  type text not null check (type in ('rivers', 'watersheds')),
  source_org text not null,
  version text not null,
  description text not null default '',
  license text not null default '',
  attribution_text text not null default '',
  created_at timestamptz not null default now()
);
create table public.hydro_files (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.hydro_products(id),
  country_iso3 text not null,
  country_name text not null,
  file_key text not null unique,
  preview_key text,
  file_size_mb numeric not null,
  feature_count integer not null default 0,
