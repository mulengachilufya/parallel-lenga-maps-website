create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text,
  plan text not null default 'basic' constraint profiles_plan_check check (plan in ('basic', 'pro', 'max')),
  account_type text,
  trial_started_at timestamptz,
  created_at timestamptz not null default now()
);
alter table public.profiles enable row level security;
create policy profiles_read_own on public.profiles for select to authenticated using (id = (select auth.uid()));
grant select on public.profiles to authenticated;

create table public.manual_payments (
  id uuid primary key default gen_random_uuid(),
  reference text not null unique,
  user_id uuid not null references auth.users(id) on delete cascade,
  user_email text not null,
  user_name text,
  region text,
  country_name text,
  plan text not null,
  account_type text not null,
  amount_usd numeric,
  amount_zmw numeric,
  currency text,
  payment_method text not null,
  sender_phone text,
  sender_name text,
  txn_reference text,
  screenshot_key text,
  status text not null default 'pending' check (status in ('pending', 'verified', 'rejected')),
  admin_note text,
  verified_at timestamptz,
  verified_by uuid references auth.users(id) on delete set null,
  submitted_at timestamptz not null default now()
);
create index manual_payments_status on public.manual_payments(status);
create index manual_payments_user on public.manual_payments(user_id);
alter table public.manual_payments enable row level security;

